const GLYPHS: ReadonlyMap<string, readonly string[]> = new Map(
  Object.entries(G).map(([ch, rows]) => [ch, rows.split(' ')]),
)

const glyphOf = (ch: string): readonly string[] =>
  GLYPHS.get(ch) ?? GLYPHS.get(ch.toUpperCase()) ?? GLYPHS.get('?')!

export const hasGlyph = (ch: string): boolean => GLYPHS.has(ch) || GLYPHS.has(ch.toUpperCase())

/** The characters of `text` as the font sees them: code points, so 🔥 is one. */
const charsOf = (text: string): string[] => [...text]

export const textWidth = (text: string, scale = 1): number => {
  const n = charsOf(text).length
  return n === 0 ? 0 : (n * ADVANCE - 1) * scale
}

/** Prints `text` at (x, y) in `color`; returns the x after it. */
export const print = (p: Pixels, x: number, y: number, text: string, color: number, scale = 1): number => {
  let cx = x
  for (const ch of charsOf(text)) {
    const rows = glyphOf(ch)
    rows.forEach((row, gy) => {
      for (let gx = 0; gx < row.length; gx++) {
        if (row[gx] !== '#') continue
        for (let sy = 0; sy < scale; sy++) {
          for (let sx = 0; sx < scale; sx++) {
            const px = cx + gx * scale + sx
            const py = y + gy * scale + sy
            if (px >= 0 && py >= 0 && px < p.w && py < p.h) p.px[py * p.w + px] = color
          }
        }
      }
    })
    cx += ADVANCE * scale
  }
  return cx
}

export type Span = readonly [text: string, color: number]

/** Prints runs of differently colored text one after another. */
export const printSpans = (p: Pixels, x: number, y: number, spans: readonly Span[], scale = 1): number =>
  spans.reduce((cx, [text, color]) => print(p, cx, y, text, color, scale), x)

export const spansWidth = (spans: readonly Span[], scale = 1): number =>
  textWidth(spans.map(([t]) => t).join(''), scale)
